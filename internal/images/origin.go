package images

import (
	"fmt"
	"net/url"
	"strings"
)

// originThumbnailResolver turns a page URL into an ordered list of candidate thumbnail URLs to try.
type originThumbnailResolver func(u *url.URL) []string

var originThumbnailResolvers = []originThumbnailResolver{
	youtubeThumbnailCandidates,
}

// resolveOriginThumbnail extracts a usable image URL from the URL of the page a listen was submitted from.
func resolveOriginThumbnail(originUrl string) (string, error) {
	u, err := url.Parse(originUrl)
	if err != nil {
		return "", fmt.Errorf("resolveOriginThumbnail: could not parse origin URL: %w", err)
	}

	for _, resolve := range originThumbnailResolvers {
		for _, candidate := range resolve(u) {
			if err := ValidateImageURL(candidate); err == nil {
				return candidate, nil
			}
		}
	}

	return "", nil
}

func youtubeThumbnailCandidates(u *url.URL) []string {
	id := youtubeVideoID(u)
	if id == "" {
		return nil
	}
	// maxresdefault isn't always generated by YouTube; hqdefault always is.
	return []string{
		fmt.Sprintf("https://i.ytimg.com/vi/%s/maxresdefault.jpg", id),
		fmt.Sprintf("https://i.ytimg.com/vi/%s/hqdefault.jpg", id),
	}
}

func youtubeVideoID(u *url.URL) string {
	host := strings.ToLower(u.Hostname())
	host = strings.TrimPrefix(host, "www.")

	var id string
	switch host {
	case "youtu.be":
		id = strings.Trim(u.Path, "/")
	case "youtube.com", "music.youtube.com", "m.youtube.com", "w.youtube.com":
		id = u.Query().Get("v")
	default:
		return ""
	}

	if !isYoutubeVideoID(id) {
		return ""
	}
	return id
}

func isYoutubeVideoID(id string) bool {
	if len(id) != 11 {
		return false
	}
	for _, r := range id {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' || r == '-') {
			return false
		}
	}
	return true
}
