func validAvatarIcon(icon string) bool {
	switch icon {
	case "", "music", "headphones", "disc", "radio", "user":
		return true
	}
	return false
}
func CreateProfileHandler(store db.ProfileStore) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		r.Body = http.MaxBytesReader(w, r.Body, 4096)
		body, err := utils.DecodeBody[struct {
			DisplayName string `json:"display_name"`
			Slug        string `json:"slug"`
			AvatarIcon  string `json:"avatar_icon"`
		}](r)
		if err != nil || !validAvatarIcon(body.AvatarIcon) {
			utils.WriteError(w, "invalid profile or icon", 400)
			return
		}
		token, err := utils.GenerateRandomString(48)
		if err != nil {
			utils.WriteError(w, "failed to generate key", 500)
			return
		}
		profile, err := store.CreateListeningProfile(r.Context(), body.DisplayName, body.Slug, body.AvatarIcon, token)
		if err != nil {
			utils.WriteError(w, "invalid, reserved or duplicate profile name/slug", 400)
			return
		}
		utils.WriteJSON(w, 201, profile) // Tokens are retrieved only from the administrative key endpoint.
	}
}
func ProfileManagementHandler(store db.ProfileStore) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		count, err := store.ProfileListenCount(r.Context(), db.ProfileID(r.Context()))
		if err != nil {
			utils.WriteError(w, "failed to count listens", 500)
			return
		}
		utils.WriteJSON(w, 200, map[string]any{"profile": middleware.ProfileFromContext(r.Context()), "listen_count": count})
	}
}
func DeleteProfileHandler(store interface {
	db.ProfileStore
	db.ImageStore
}) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		p := middleware.ProfileFromContext(r.Context())
		body, err := utils.DecodeBody[struct {
			DisplayName string `json:"display_name"`
			ListenCount *int64 `json:"listen_count"`
		}](r)
		if err != nil || body.DisplayName != p.DisplayName || body.ListenCount == nil || *body.ListenCount < 0 {
			utils.WriteError(w, "confirm profile name and listen count", 400)
			return
		}
		if err = store.DeleteListeningProfile(r.Context(), p.ID, body.DisplayName, *body.ListenCount); err != nil {
			utils.WriteError(w, "profile changed; refresh and confirm again", 409)
			return
		}
		memkv.Store.Delete(fmt.Sprintf("now-playing:%d", p.ID))
		cleanupProfileImage(store, p.AvatarImageID)
		w.WriteHeader(204)
	}
}

// UUIDs are generated by the server, never supplied by a profile form. Only remove
// files after commit and after checking references across profiles and catalog.
func cleanupProfileImage(store db.ImageStore, old *string) {
	if old == nil {
		return
	}
	id, err := uuid.Parse(*old)
	if err != nil {
		return
	}
	used, err := store.ImageHasAssociation(context.Background(), id)
	if err == nil && !used {
		_ = imagecache.DeleteImage(id)
	}
}
func ProfileAvatarHandler(store interface {
	db.ProfileStore
	db.ImageStore
}) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		p := middleware.ProfileFromContext(r.Context())
		var image, icon *string
		if r.Method != "DELETE" {
			r.Body = http.MaxBytesReader(w, r.Body, 5<<20)
			if err := r.ParseMultipartForm(1 << 20); err != nil {
				utils.WriteError(w, "avatar must be a multipart upload up to 5 MiB", 400)
				return
			}
			defer r.MultipartForm.RemoveAll()
			value := r.FormValue("icon")
			if !validAvatarIcon(value) {
				utils.WriteError(w, "invalid avatar icon", 400)
				return
			}
			if value != "" {
				icon = &value
			}
			f, _, err := r.FormFile("image")
			if err == nil {
				defer f.Close()
				buf := make([]byte, 512)
				n, readErr := f.Read(buf)
				if (readErr != nil && readErr != io.EOF) || !strings.HasPrefix(http.DetectContentType(buf[:n]), "image/") {
					utils.WriteError(w, "invalid image", 400)
					return
				}
				_, _ = f.Seek(0, io.SeekStart)
				id := uuid.New()
				if err = imagecache.SaveImage(id, f); err != nil {
					_ = imagecache.DeleteImage(id)
					utils.WriteError(w, "could not process image", 400)
					return
				}
				value := id.String()
				image = &value
			} else if err != http.ErrMissingFile {
				utils.WriteError(w, "invalid image upload", 400)
				return
			}
		}
		if err := store.SetProfileAvatar(r.Context(), p.ID, image, icon); err != nil {
			cleanupProfileImage(store, image)
			utils.WriteError(w, "could not update avatar", 500)
			return
		}
		cleanupProfileImage(store, p.AvatarImageID)
		updated, err := store.GetListeningProfileByID(r.Context(), p.ID)
		if err != nil {
			utils.WriteError(w, "profile not found", 404)
			return
		}
		utils.WriteJSON(w, 200, updated)
	}
}
